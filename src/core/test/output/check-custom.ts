import { z } from "zod";
import { json, validateEnv } from "type-envgen";

export const envSchema = z.object({
  ADMIN_EMAIL: z.email(),
  API_URL: z.url(),
  APP_ID: z.uuid(),
  APP_NAME: z.string().min(1),
  BASE_URL: z.string(),
  BIND_HOST_IPV4: z.ipv4(),
  BIND_HOST_IPV6: z.ipv6(),
  BUILD_TIMESTAMP: z.iso.datetime(),
  CSV_LIST: z.string(),
  CUSTOM_DATE: z.iso.date(),
  CUSTOM_DATETIME: z.iso.datetime(),
  CUSTOM_IPV4: z.ipv4(),
  CUSTOM_IPV6: z.ipv6(),
  DATABASE_URL: z.url(),
  DEBUG: z.stringbool(),
  DEFAULT_HOST: z.string().default("localhost"),
  DEFAULT_PORT: z.coerce.number().int().default(8080),
  DOUBLE_QUOTED: z.string(),
  EMPTY_QUOTED: z.string(),
  EMPTY_VALUE: z.string(),
  ESCAPED_NEWLINES: z.string(),
  EXPORTED_VAR: z.string(),
  FEATURE_FLAG: z.stringbool(),
  FLOAT: z.coerce.number(),
  HOST: z.string(),
  INLINE_COMMENT: z.string(),
  JSON_ARRAY: json(z.array(z.string())),
  JSON_OBJECT: json(z.object({ key: z.string(), n: z.number() })),
  LOG_LEVEL: z.enum(["debug","info","warn","error"]),
  NEGATIVE: z.coerce.number().int(),
  NODE_ENV: z.enum(["development","production","test"]),
  OPTIONAL_TOKEN: z.string().optional(),
  PORT: z.coerce.number().int().min(1).max(65535),
  PRIVATE_KEY: z.string(),
  REDIS_URL: z.url(),
  RELEASE_DATE: z.iso.date(),
  SECRET_KEY: z.string(),
  SILENT: z.coerce.number().int(),
  SINGLE_QUOTED: z.string(),
  SPACES_AROUND: z.string(),
  VALUE_WITH_EQUALS: z.string(),
  VALUE_WITH_HASH: z.string(),
  VERBOSE: z.stringbool(),
  ZERO: z.coerce.number().int(),
});

export const env = validateEnv(envSchema, process.env);
export type Env = z.infer<typeof envSchema>;
export const isProd = true;
